import { describe, it, expect } from 'vitest';
import { generateTypes } from '../generate.js';

describe('generateTypes', () => {
  it('generates types for flags with variants', () => {
    const output = generateTypes({
      version: 1,
      flags: {
        'checkout-flow': {
          enabled: true,
          variants: [
            { name: 'control', weight: 50 },
            { name: 'new-flow', weight: 50 },
          ],
        },
      },
    });
    expect(output).toContain("'checkout-flow'");
    expect(output).toContain("'control' | 'new-flow'");
  });

  it('generates never for flags without variants', () => {
    const output = generateTypes({
      version: 1,
      flags: {
        'simple-flag': { enabled: true },
      },
    });
    expect(output).toContain("'simple-flag'");
    expect(output).toContain('never');
  });

  it('sorts flag names', () => {
    const output = generateTypes({
      version: 1,
      flags: {
        'z-flag': { enabled: true },
        'a-flag': { enabled: true },
      },
    });
    const aIdx = output.indexOf('a-flag');
    const zIdx = output.indexOf('z-flag');
    expect(aIdx).toBeLessThan(zIdx);
  });

  it('includes auto-generated header', () => {
    const output = generateTypes({ version: 1, flags: {} });
    expect(output).toContain('Auto-generated by tinyflag');
  });
});
